# ── Find a Unicode/Cyrillic-capable font ─────────────────────────────────────
def find_font(name_hint):
    candidates = [
        f"/usr/share/fonts/truetype/dejavu/DejaVu{name_hint}.ttf",
        f"/usr/share/fonts/truetype/liberation/Liberation{name_hint}.ttf",
        f"/usr/share/fonts/truetype/freefont/Free{name_hint}.ttf",
        f"/usr/share/fonts/truetype/ubuntu/Ubuntu-R.ttf",
        f"/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf",
    ]
    for c in candidates:
        if os.path.exists(c):
            return c
    hits = glob.glob("/usr/share/fonts/**/*.ttf", recursive=True)
    return hits[0] if hits else None

regular_path = find_font("Sans")
