# ── Styles ─────────────────────────────────────────────────────────────────────
def S(name, **kw):
    base = dict(fontName="DocFont", fontSize=10, leading=14,
                textColor=C_BLACK, spaceAfter=4, spaceBefore=2,
                alignment=TA_LEFT)
    base.update(kw)
    return ParagraphStyle(name, **base)

