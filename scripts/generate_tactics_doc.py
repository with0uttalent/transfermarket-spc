def p(text, st=None):  return Paragraph(text, st or sBody)
def h1(text):          return Paragraph(f"  {text}", sH1)
def h2(text):          return Paragraph(text, sH2)
def sp(n=4):           return Spacer(1, n*mm)
def hr(c=GOLD):        return HRFlowable(width="100%", thickness=0.8, color=c, spaceAfter=3*mm)
def bull(text):        return Paragraph(f"• {text}", sBull)
def note(text):        return Paragraph(f"  {text}", sNote)
def warn(text):        return Paragraph(f"⚠  {text}", sWarn)
def formula(text):     return Paragraph(text, sFormula)

def kv(rows, cw=None):
    W = A4[0] - 40*mm
    cw = cw or [W*0.38, W*0.62]
