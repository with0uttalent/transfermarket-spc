# ── Font ──────────────────────────────────────────────────────────────────────
def find_font(hint):
    for p in [
        f"/usr/share/fonts/truetype/dejavu/DejaVu{hint}.ttf",
        f"/usr/share/fonts/truetype/liberation/Liberation{hint}.ttf",
        f"/usr/share/fonts/truetype/freefont/Free{hint}.ttf",
    ]:
        if os.path.exists(p): return p
    hits = glob.glob("/usr/share/fonts/**/*.ttf", recursive=True)
    return hits[0] if hits else None

pdfmetrics.registerFont(TTFont("F",  find_font("Sans")))
