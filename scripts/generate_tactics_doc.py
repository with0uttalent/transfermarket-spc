def B(t): return f'<font name="FB">{t}</font>'
def G(t): return f'<font color="#1a5c2a"><b>{t}</b></font>'
def R(t): return f'<font color="#a00000"><b>{t}</b></font>'
def Au(t): return f'<font color="#c8a217"><b>{t}</b></font>'
