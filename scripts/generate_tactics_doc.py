# ── Styles ────────────────────────────────────────────────────────────────────
def S(name, **kw):
    d = dict(fontName="F", fontSize=10, leading=15, textColor=BLACK,
             spaceAfter=4, spaceBefore=2, alignment=TA_LEFT)
    d.update(kw)
    return ParagraphStyle(name, **d)

